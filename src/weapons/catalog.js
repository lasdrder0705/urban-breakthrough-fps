  const BY_ID = Object.create(null);
  for (const fac of ['UA', 'RU']) {
    for (const w of WEAPONS[fac]) {
      BY_ID[w.id] = w;
    }
  }
  for (const k in SPECIAL_WEAPONS) {
    BY_ID[k] = SPECIAL_WEAPONS[k];
  }

  function normFaction(faction) {
    return faction === 'RU' ? 'RU' : 'UA';
  }

  function getSlotIndex(slotOrId) {
    if (typeof slotOrId === 'number') {
      return Math.max(0, Math.min(5, slotOrId | 0));
    }
    if (typeof slotOrId === 'string') {
      const low = slotOrId.toLowerCase();
      const idx = SLOT_NAMES.indexOf(low);
      if (idx >= 0) return idx;
      if (BY_ID[low] && BY_ID[low].slot >= 0) return BY_ID[low].slot;
      const num = parseInt(low, 10);
      if (!isNaN(num) && num >= 0 && num <= 5) return num;
    }
    return 0;
  }

  function get(slotOrId, faction) {
    if (typeof slotOrId === 'object' && slotOrId && slotOrId.id) {
      return slotOrId;
    }
    const fac = normFaction(faction);
    if (typeof slotOrId === 'string') {
      const low = slotOrId.toLowerCase();
      if (BY_ID[low]) return BY_ID[low];
      const slotIdx = SLOT_NAMES.indexOf(low);
      if (slotIdx >= 0) return WEAPONS[fac][slotIdx];
      const num = parseInt(low, 10);
      if (!isNaN(num) && num >= 0 && num <= 5) return WEAPONS[fac][num];
    }
    if (typeof slotOrId === 'number') {
      const idx = Math.max(0, Math.min(5, slotOrId | 0));
      return WEAPONS[fac][idx];
    }
    return WEAPONS[fac][0];
  }

  function getSlotList(faction) {
    return WEAPONS[normFaction(faction)].slice();
  }

  function getAll() {
    return WEAPONS.UA.concat(WEAPONS.RU);
  }

  function getSpecial(id) {
    return SPECIAL_WEAPONS[id] || null;
  }

  function computeRecoilImpulse(spec, burstCount, isAds, isCrouching) {
    const s = spec || WEAPONS.UA[0];
    const adsScale = isAds ? 0.68 : 1.0;
    const crouchScale = isCrouching ? 0.78 : 1.0;
    const firstShotMult = burstCount <= 1 ? 1.18 : 1.0;
    const fatigue = 1.0 + Math.min(burstCount, 14) * 0.035;
    const pitch = s.recoilPitch * adsScale * crouchScale * firstShotMult * (0.9 + Math.random() * 0.2);
    const swayDir = Math.sin(burstCount * 1.73 + (s.slot || 0)) * 0.45 + (Math.random() * 2 - 1) * 0.75;
    const yaw = s.recoilYaw * adsScale * crouchScale * fatigue * swayDir;
    const kick = (s.recoilKick || 0.05) * (isAds ? 0.62 : 1.0) * crouchScale;
    const roll = (s.recoilRoll || 0.025) * (Math.random() < 0.5 ? -1 : 1) * adsScale;
    return { pitch, yaw, kick, roll };
  }

